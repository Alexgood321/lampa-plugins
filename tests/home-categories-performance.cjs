'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../home_categories.js'),'utf8');
new vm.Script(source);
assert.match(source,/function scheduleDOMScan\(checkMenu\)/);
assert.match(source,/function relevantNode\(node\)/);
assert.match(source,/HC_PERF\.scans\+\+/);
assert.match(source,/syncControllerItems\(rankFor\)/);
assert.ok(!/setInterval\s*\(/.test(source),'must not poll every 300ms or leave another interval');
assert.ok(!/intervalTimer/.test(source),'old timer must be removed');
assert.match(source,/domObserver\.observe\(document\.body, \{ childList: true, subtree: true \}\)/);
assert.match(source,/window\.plugin_home_categories_destroy\s*=\s*function/);
console.log('PASS Home Categories: event-driven DOM, coalesced mutations, cached ranks, profiler, cleanup');
